// Passeio no navegador real (Chrome local + puppeteer-core): loja, checkout, assistencia, conta e gestao.
// Uso: node tools/testes/ui.cjs   (CHROME_PATH e BASE opcionais). Cria dados de teste: so no banco local.
const puppeteer = require('puppeteer-core');
const OUT = require('path').join(require('os').tmpdir(), 'doutor-ui-shots') + '/';
const BASE = process.env.BASE || 'http://localhost:8093/';
const fs = require('fs'); fs.mkdirSync(OUT, { recursive: true });
const sleep = ms => new Promise(r => setTimeout(r, ms));
const errors = [];
let pass = 0, fail = 0;
const ok = (c, m, x) => { if (c) { pass++; console.log('  ok  ', m); } else { fail++; console.log('  FAIL', m, x || ''); } };

(async () => {
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  await page.setViewport({ width: 1280, height: 900 });
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text() + ' @ ' + (m.location() && m.location().url)); });
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('response', r => { if (r.status() >= 500) errors.push('HTTP ' + r.status() + ' ' + r.url()); });
  const go = async h => { await page.evaluate(x => { location.hash = x; }, h); await sleep(700); };
  const text = () => page.evaluate(() => document.body.innerText);
  const click = async sel => { try { await page.waitForSelector(sel, { timeout: 5000 }); } catch (e) { await page.screenshot({ path: OUT + 'erro.png' }); console.log('HASH', await page.evaluate(() => location.hash), (await page.evaluate(() => document.body.innerText)).slice(0, 600)); throw e; } await page.click(sel); await sleep(450); };
  const type = async (sel, v) => { await page.waitForSelector(sel, { timeout: 5000 }); await page.click(sel, { clickCount: 3 }); await page.type(sel, v); };
  const shot = n => page.screenshot({ path: OUT + n + '.png' });

  console.log('Loja');
  await page.goto(BASE, { waitUntil: 'networkidle0' });
  await sleep(500);
  let t = await text();
  ok(t.includes('Mais procurados') && t.includes('iPhone 16'), 'home carrega catálogo da API');
  ok(!/demonstr|fictíci|protótipo|Demonstração SMG|Restaurar dados/i.test(t), 'home sem textos de demonstração');
  await shot('01-home');
  await go('loja-celulares');
  t = await text();
  ok(t.includes('Galaxy S24 FE') && t.includes('resultado'), 'catálogo de celulares');
  await go('produto-p01');
  await click('button[data-act="pick"][data-v="128 GB"]');
  await click('button[data-act="pick"][data-v="Preto"]');
  t = await text();
  ok(/Adicionar à sacola/.test(t), 'variação com estoque disponível em Itaim', t.slice(0, 300));
  await shot('02-produto');
  await click('button[data-act="pd-add"]');
  await go('sacola');
  t = await text();
  ok(t.includes('Sua sacola') && t.includes('iPhone 16'), 'sacola com item');
  await go('checkout');
  await click('button[data-act="ck-next"]');
  const phone = '1197' + String(Date.now()).slice(-7);
  await type('#ck-name', 'Maria Navegador');
  await type('#ck-phone', phone);
  await click('button[data-act="ck-next"]');
  await click('button[data-act="ck-next"]');
  await shot('03-checkout-pagamento');
  await click('button[data-act="ck-confirm"]');
  await sleep(1200);
  t = await text();
  const ped = (t.match(/PED-\d+/) || [])[0];
  ok(t.includes('Pedido recebido') && ped, 'pedido criado e página do pedido aberta', t.slice(0, 300));
  await shot('04-pedido');

  console.log('Assistência');
  await go('assistencia');
  await click('button[data-act="svc-pick"][data-svc="Troca de bateria"]');
  await type('#sv-name', 'Maria Navegador');
  await type('#sv-phone', phone);
  await page.select('#sv-brand', 'Apple'); await sleep(300);
  await type('#sv-model', 'iPhone 12');
  await type('#sv-desc', 'Bateria acaba antes do almoço');
  await click('#svc-form button[type=submit]');
  await sleep(1200);
  t = await text();
  const os = (t.match(/OS-\d+/) || [])[0];
  ok(t.includes('Solicitação enviada') && os, 'OS criada e acompanhamento aberto', t.slice(0, 300));
  await shot('05-os');

  console.log('Acompanhar (aparelho novo, sem token)');
  await page.evaluate(() => localStorage.removeItem('kc-acessos'));
  await go('acompanhar');
  await go('pedido-' + ped.slice(4));
  t = await text();
  ok(t.includes('confirme o telefone'), 'pedido sem token pede telefone');
  await type('#lk-phone', '11900000000');
  await click('form[data-form="unlock"] button[type=submit]');
  await sleep(800);
  t = await text();
  ok(/Não encontramos/.test(t), 'telefone errado recusado na tela');
  await type('#lk-phone', phone);
  await click('form[data-form="unlock"] button[type=submit]');
  await sleep(1000);
  t = await text();
  ok(t.includes('Acompanhar pedido') && t.includes('Maria Navegador'), 'telefone certo libera o pedido');
  await go('acompanhar');
  await type('#track', os);
  await type('#track-phone', phone);
  await click('form[data-form="track"] button[type=submit]');
  await sleep(1200);
  t = await text();
  ok(t.includes('Acompanhar assistência') && t.includes('iPhone 12'), 'acompanhar OS por código + telefone');

  console.log('Gestão');
  await go('gestao');
  t = await text();
  ok(t.includes('Entrar na gestão'), 'gestão pede login');
  await shot('06-login');
  await type('#al-email', 'admin@doutordocelular.com.br');
  await type('#al-pass', 'admin123');
  await click('form[data-form="adm-login"] button[type=submit]');
  await sleep(2000);
  t = await text();
  ok(t.includes('Faturamento realizado') && t.includes('Pedidos recentes'), 'dashboard após login');
  ok(!/Dados simulados|demonstr/i.test(t), 'dashboard sem textos de demonstração');
  await shot('07-dashboard');
  await go('gestao-pedidos');
  await sleep(500);
  await click(`tr[data-act="adm-open"][data-id="${ped.slice(4)}"]`);
  await sleep(800);
  await click('button[data-act="ord-set"][data-v="confirmado"]');
  await sleep(1500);
  t = await text();
  ok(t.includes('Estoque baixado em'), 'confirmar pedido pela gaveta baixa estoque');
  await shot('08-pedido-gaveta');
  await page.keyboard.press('Escape'); await sleep(300);
  await go('gestao-assistencia');
  await sleep(600);
  await click(`button[data-act="adm-open"][data-id="${os.slice(3)}"]`);
  await sleep(800);
  await type(`#qv-${os.slice(3)}`, '289,90');
  await click('form[data-form="quote"] button[type=submit]');
  await sleep(1200);
  t = await text();
  ok(/aguardando o cliente/i.test(t), 'orçamento registrado na OS');
  await page.keyboard.press('Escape'); await sleep(300);
  await go('gestao-produtos');
  await sleep(500);
  await click('tr[data-act="adm-open"][data-id="a01"]');
  await sleep(500);
  t = await text();
  ok(/variações e estoque por unidade/i.test(t) && /adicionar opção/i.test(t), 'ficha do produto com editor de variações');
  await type('#pe-price', '42,90');
  await click('form[data-form="prod-edit"] button[type=submit]');
  await sleep(1200);
  t = await text();
  ok(t.includes('Produto salvo') || t.includes('42,90'), 'produto salvo pelo painel');
  await shot('09-produto-gaveta');
  await page.keyboard.press('Escape'); await sleep(300);
  await go('gestao-estoque');
  await click('button[data-act="adm-stk-unit"][data-v="suzano"]');
  await type('#stk-q', 'Capa transparente');
  await sleep(600);
  const before = await page.$eval('input[data-stk-set]', el => el.value);
  await click('button[data-act="stk-adj"][data-d="1"]');
  await sleep(1000);
  const after = await page.$eval('input[data-stk-set]', el => el.value);
  ok(Number(after) === Number(before) + 1, 'botão + lança estoque', [before, after]);
  await shot('10-estoque');
  for (const m of ['clientes', 'unidades', 'oportunidades', 'ajustes']) {
    await go('gestao-' + m); await sleep(900);
    t = await text();
    ok(!/Não foi possível carregar/.test(t), 'módulo ' + m + ' carrega');
  }
  await shot('11-ajustes');
  await go('gestao-unidades'); await sleep(900);
  await type('#un-addr-itaim', 'Rua Exemplo, 100, Itaim Paulista');
  await click('form[data-form="unit"][data-id="itaim"] button[type=submit]');
  await sleep(1500);

  console.log('Cliente aprova orçamento e cria conta');
  await go('os-' + os.slice(3));
  await sleep(2000);
  t = await text();
  ok(t.includes('Aprovar orçamento'), 'cliente vê orçamento com botão de aprovar');
  await click('button[data-act="quote-ask"][data-v="aprovar"]');
  await click('button[data-act="quote-do"]');
  await sleep(1200);
  t = await text();
  ok(t.includes('Aprovado por você'), 'aprovação registrada');
  await go('atendimento');
  t = await text();
  ok(t.includes('Rua Exemplo, 100'), 'endereço da unidade editado aparece na loja');
  await go('conta');
  await click('button[data-act="acc-mode"][data-v="cadastro"]');
  await type('#ac-name', 'Maria Navegador');
  await type('#ac-phone', phone);
  await type('#ac-pass', 'senha123');
  await click('form[data-form="acc"] button[type=submit]');
  await sleep(1000);
  t = await text();
  ok(t.includes('informe o código') || t.includes('código de um deles'), 'cadastro pede código por já haver histórico');
  await type('#ac-code', ped);
  await click('form[data-form="acc"] button[type=submit]');
  await sleep(1500);
  t = await text();
  ok(t.includes('Histórico') && t.includes(ped) && t.includes(os), 'Minha conta mostra pedido e OS');
  await shot('12-conta');

  console.log('Celular (375px)');
  await page.setViewport({ width: 375, height: 812, isMobile: true, hasTouch: true });
  await go('loja');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  ok(!overflow, 'sem rolagem horizontal no celular');
  await shot('13-mobile-loja');
  await go('gestao-pedidos'); await sleep(800);
  await shot('14-mobile-gestao');

  console.log('\nErros no navegador:', errors.length ? errors : 'nenhum');
  const unexpected = errors.filter(e => !/status of (404|409)/.test(e));
  console.log('Respostas 4xx esperadas (telefone errado / cadastro pede código):', errors.length - unexpected.length);
  ok(unexpected.length === 0, 'sem erros de JavaScript nem respostas 5xx', unexpected);
  console.log(`Resultado UI: ${pass} ok, ${fail} falhas`);
  await browser.close();
  process.exit(fail ? 1 : 0);
})().catch(async e => { console.error(e); process.exit(2); });
